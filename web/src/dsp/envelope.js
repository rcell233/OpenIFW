function clock(knots, value) {
  value = Math.max(0, Math.min(10, value));
  let i = 1;
  while (i < knots.length - 1 && value > knots[i][0]) i++;
  const [x0, y0] = knots[i - 1],
    [x1, y1] = knots[i];
  return y0 * Math.exp((Math.log(y1 / y0) * (value - x0)) / (x1 - x0));
}
export const attackSeconds = (value) => clock(ATTACK, value);
export const decayHalfSeconds = (value) => clock(HALF, value);
export function nativeDecay(u) {
  const x = Math.max(0, u) * 100,
    i = Math.floor(x);
  if (i >= CURVE.length - 1) return 0;
  return CURVE[i] + (CURVE[i + 1] - CURVE[i]) * (x - i);
}
export class Envelope {
  constructor(sr) {
    this.sr = sr;
    this.level = 0;
    this.stage = 'idle';
    this.releaseStart = 0;
    this.time = 0;
  }
  configure(a, d, s, r, retrigger) {
    this.a = attackSeconds(a);
    this.dHalf = decayHalfSeconds(d);
    this.rHalf = decayHalfSeconds(r);
    this.s = Math.max(0, Math.min(1, s / 10));
    this.retrigger = retrigger;
  }
  gate(open, legato = false) {
    if (open) {
      if (!legato || this.retrigger) {
        this.stage = 'attack';
        this.time = 0;
        this.level = 0;
      }
    } else if (this.stage !== 'idle' && this.stage !== 'release') {
      this.stage = 'release';
      this.releaseStart = this.level;
      this.time = 0;
    }
  }
  tick(rate = 1) {
    this.time += rate / this.sr;
    if (this.stage === 'attack') {
      this.level = Math.min(1, this.time / this.a);
      if (this.level >= 1) {
        this.stage = 'decay';
        this.time = 0;
      }
    } else if (this.stage === 'decay') {
      const v = nativeDecay(this.time / this.dHalf);
      this.level = this.s + (1 - this.s) * v;
      if (v === 0) {
        this.stage = 'sustain';
        this.level = this.s;
      }
    } else if (this.stage === 'sustain') this.level = this.s;
    else if (this.stage === 'release') {
      const v = nativeDecay(this.time / this.rHalf);
      this.level = this.releaseStart * v;
      if (v === 0) {
        this.stage = 'idle';
        this.level = 0;
      }
    }
    return this.level;
  }
}
